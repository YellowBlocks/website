/**
 * Locale configuration, shared by server and client code.
 *
 * URL scheme
 * - Dutch is the default and lives at the root: /oplossingen/intune-assessment
 * - English lives under /en with English path segments: /en/solutions/intune-assessment
 *
 * Internally every route lives under app/[lang]/ with Dutch folder names. Rewrites in
 * next.config.ts map the public URLs onto those routes, so pages stay statically generated.
 * Code always links with the internal Dutch path (e.g. "/oplossingen"); `localizePath`
 * turns that into the public URL for the active locale.
 */
export const locales = ["nl", "en"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "nl";

export const isLocale = (v: unknown): v is Locale => typeof v === "string" && (locales as readonly string[]).includes(v);

export const localeMeta: Record<Locale, { label: string; name: string; ogLocale: string; htmlLang: string }> = {
  nl: { label: "NL", name: "Nederlands", ogLocale: "nl_NL", htmlLang: "nl" },
  en: { label: "EN", name: "English", ogLocale: "en_GB", htmlLang: "en" },
};

/** Top-level route folders: Dutch (internal) -> English (public). Used by the rewrites. */
export const routeSegmentsNlToEn: Record<string, string> = {
  oplossingen: "solutions",
  werkwijze: "approach",
  "over-ons": "about",
  inzichten: "insights",
  voorwaarden: "terms",
};

/** Slugs that differ per language. English params are generated by the page itself. */
export const slugsNlToEn: Record<string, string> = {
  "tenant-continuiteit": "tenant-continuity",
};
export const slugsEnToNl: Record<string, string> = Object.fromEntries(Object.entries(slugsNlToEn).map(([nl, en]) => [en, nl]));

/** Dutch path segment -> English path segment. Segments not listed are identical. */
export const segmentsNlToEn: Record<string, string> = { ...routeSegmentsNlToEn, ...slugsNlToEn };

export const segmentsEnToNl: Record<string, string> = Object.fromEntries(Object.entries(segmentsNlToEn).map(([nl, en]) => [en, nl]));

const isInternal = (href: string) =>
  href.startsWith("/") && !href.startsWith("//") && !/^\/(api|brand|_next)(\/|$)/.test(href) && !/\.[a-z0-9]+$/i.test(href.split(/[?#]/)[0]);

/** Internal (Dutch) path -> public path for a locale. Query strings and hashes are kept. */
export function localizePath(href: string, lang: Locale): string {
  if (lang === defaultLocale || !isInternal(href)) return href;
  const match = href.match(/^([^?#]*)(.*)$/);
  const path = match?.[1] ?? href;
  const rest = match?.[2] ?? "";
  const mapped = path
    .split("/")
    .map((seg) => segmentsNlToEn[seg] ?? seg)
    .join("/");
  return `/${lang}${mapped === "/" ? "" : mapped}${rest}`;
}

/**
 * Public or internal path -> { lang, internal Dutch path }. During server rendering
 * usePathname() returns the rewritten internal path (/nl/..., /en/oplossingen/...),
 * in the browser the public one; both resolve to the same result.
 */
export function parsePublicPath(pathname: string): { lang: Locale; path: string } {
  const m = pathname.match(/^\/(en|nl)(\/.*)?$/);
  if (!m) return { lang: defaultLocale, path: pathname || "/" };
  if (m[1] === "nl") return { lang: "nl", path: m[2] ?? "/" };
  const rest = m[2] ?? "/";
  const path = rest
    .split("/")
    .map((seg) => segmentsEnToNl[seg] ?? seg)
    .join("/");
  return { lang: "en", path: path || "/" };
}

/** Same page in another locale, from the current public pathname. */
export const switchLocalePath = (pathname: string, to: Locale) => localizePath(parsePublicPath(pathname).path, to);
